const B = F.frame([120, 290, 760, 170], xl, [-0.2, 1.2]).axes({ xticks: [0, 250, 500, 750, 1000, 1250], yticks: [0, 0.4, 0.8, 1.2], tick: 22, xfmt: () => "", ylabel: "유효전력 $P$ [pu]" });
