F.label(895, G.y(3), `보정: 최대 ${D.freeze.ddmax.toFixed(1)}°<br>제거 후 포화 ${D.freeze.sat_end_ms.toFixed(0)} ms`, { anchor: "l", size: 20, color: C.blue, weight: 700 });
F.done();
