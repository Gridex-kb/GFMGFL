shade(F, A, 0, 150);
A.hline(1.2, { color: C.red, width: 2, dash: "6 6" });
A.plot(D.GFL.t, D.GFL.I, { color: C.orange, width: 3 });
A.plot(D.nofreeze.t, D.nofreeze.I, { color: C.purple, width: 3, dash: "10 8" });
